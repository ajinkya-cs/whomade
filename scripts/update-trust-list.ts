// Regenerates src/trust-list.ts from the official C2PA trust list.
import { writeFile } from 'node:fs/promises';

const REPO = 'c2pa-org/conformance-public';
const PATH = 'trust-list/C2PA-TRUST-LIST.pem';

const [commit] = await (await fetch(`https://api.github.com/repos/${REPO}/commits?path=${PATH}&per_page=1`)).json();
const pem = await (await fetch(`https://raw.githubusercontent.com/${REPO}/${commit.sha}/${PATH}`)).text();
if (!pem.includes('BEGIN CERTIFICATE')) throw new Error('Unexpected trust list content');

await writeFile(
  new URL('../src/trust-list.ts', import.meta.url),
  `// Generated by scripts/update-trust-list.ts. Do not edit.
// C2PA trust list, https://github.com/${REPO}/blob/${commit.sha}/${PATH}
// (c) C2PA, licensed under CC BY 4.0.
export const anchors: string = \`${pem.trim().replace(/[`\\$]/g, '\\$&')}\`;
`,
);
console.log(`Trust list updated to ${REPO}@${commit.sha.slice(0, 12)}`);
