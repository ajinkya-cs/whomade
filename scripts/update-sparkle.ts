// Regenerates src/sparkle.ts: the alpha map of Gemini's visible watermark, captured on black.
import { writeFile } from 'node:fs/promises';
import { PNG } from 'pngjs';

const REPO = 'GargantuaX/gemini-watermark-remover';
const COMMIT = 'c596ae7b03d63a32eb952bca81a18c8111e88e89';
const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/src/assets/bg_96.png`;

const png = PNG.sync.read(Buffer.from(await (await fetch(url)).arrayBuffer()));
const alpha = new Uint8Array(png.width * png.height);
for (let i = 0; i < alpha.length; i++) {
  alpha[i] = Math.max(png.data[i * 4]!, png.data[i * 4 + 1]!, png.data[i * 4 + 2]!);
}

await writeFile(
  new URL('../src/sparkle.ts', import.meta.url),
  `// Generated by scripts/update-sparkle.ts. Do not edit.
// ${png.width}x${png.height} alpha map (0-255) from https://github.com/${REPO}/blob/${COMMIT}/src/assets/bg_96.png
// (c) the gemini-watermark-remover authors, MIT License.
export const SPARKLE_SIZE = ${png.width};
export const SPARKLE: string = '${Buffer.from(alpha).toString('base64')}';
`,
);
console.log(`Sparkle updated from ${REPO}@${COMMIT.slice(0, 12)}`);
